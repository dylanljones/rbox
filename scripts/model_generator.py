@dataclass
class StructField:
    name: str
    type: str


@dataclass
class Model:
    name: str
    fields: list[StructField]
    id: str


def parse_models(file: Path | str) -> Iterator[Model]:
    with open(file, "r") as f:
        while line := f.readline():
            if line.startswith("pub struct ") and "DateString" not in line:
                model_name = line.split()[2].split("{")[0]
                model_name = model_name.replace("Py", "")

                field_line = f.readline().strip()
                fields = list()
                while not field_line.startswith("}"):
                    if field_line.startswith("pub"):
                        _, field_name, field_type = field_line.split()
                        field_name = field_name.strip().rstrip(":")
                        field_type = field_type.strip().rstrip(",")
                        field = StructField(name=field_name, type=field_type)
                        fields.append(field)

                    field_line = f.readline().strip()
                id_field = fields[0].name
                yield Model(name=model_name, fields=fields, id=id_field)


def get_py_type(field_type: str) -> str:
    if "Date" in field_type:
        field_type = "Py<PyDateTime>"
    if "Rc" in field_type:
        field_type = "Py<PyList>"
    return field_type


def get_js_type(field_type: str) -> str:
    if "Date" in field_type:
        field_type = "JsDate"
    if "Rc" in field_type:
        field_type = "Vec<JsDjmdPlaylistTreeItem>"
    return field_type


def get_py_fields(fields: list[StructField]) -> str:
    indent = "    "
    lines = list()
    for field in fields:
        py_type = get_py_type(field.type)
        lines.append(f"pub {field.name}: {py_type},")
    return f"\n{indent}".join(lines)


def get_js_fields(fields: list[StructField]) -> str:
    indent = "    "
    lines = list()
    for field in fields:
        py_type = get_js_type(field.type)
        lines.append(f"pub {field.name}: {py_type},")
    return f"\n{indent}".join(lines)


def get_into_py_fields(fields: list[StructField]) -> str:
    indent = "    "
    lines = list()
    for field in fields:
        if "Date" in field.type:
            val = f"self.{field.name}.into_pyobject(py)?.into()"
        else:
            val = f"self.{field.name}"
        lines.append(f"{field.name}: {val},")
    return f"\n{3 * indent}".join(lines)


def get_into_js_fields(fields: list[StructField]) -> str:
    indent = "    "
    lines = list()
    for field in fields:
        if "Date" in field.type:
            val = f"datetime_to_js_date(env, &self.{field.name})"
        else:
            val = f"self.{field.name}"
        lines.append(f"{field.name}: {val},")
    return f"\n{3 * indent}".join(lines)


def get_from_py_fields(fields: list[StructField]) -> str:
    indent = "    "
    lines = list()
    for field in fields:
        if "Date" in field.type:
            val = f"model.{field.name}.extract::<DateTime<Utc>>(py).unwrap()"
        elif "String" in field.type:
            val = f"model.{field.name}.clone()"
        else:
            val = f"model.{field.name}"
        lines.append(f"{field.name}: {val},")
    return f"\n{3 * indent}".join(lines)


def get_from_js_fields(fields: list[StructField]) -> str:
    indent = "    "
    lines = list()
